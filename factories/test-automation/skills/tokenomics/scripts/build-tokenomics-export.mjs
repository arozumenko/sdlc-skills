#!/usr/bin/env node
// build-tokenomics-export.mjs — reshape a batch's cost.json into one row of the
// cross-factory tokenomics dataset (the same schema the manual-qa bundle
// exports to), so test-automation batches sit alongside other factories' rows.
//
//   node build-tokenomics-export.mjs [repo] --batch <slug> [--profile <path>]
//        [--out <file>] [--stdout]
//   node build-tokenomics-export.mjs --compare <a.cost.json> <b.cost.json>
//
// IDENTITY IS PROJECT-LOCAL, NEVER BUNDLED. The factory header (factory_id,
// factory_name, owner_group, …) comes from a hand-authored profile file the
// project keeps at .agents/telemetry/factory-profile.json — copy
// ../templates/factory-profile.template.json there and fill it in once. The
// bundle ships only this generic plumbing; no organisation identifiers.
//
// DOLLAR HONESTY: every figure is carried from cost.json, which only ever
// holds measured values (ccusage-metered on Claude; billed credits on
// Copilot). Fields the pipeline cannot measure are null, never invented.
//
// STDLIB ONLY. Read-only except --out.
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { updateBatchCosts } from './batch-cost.mjs';

function safeParse(s) { try { return JSON.parse(s); } catch { return null; } }
const round = (v, p = 2) => (typeof v === 'number' ? Math.round(v * 10 ** p) / 10 ** p : null);

export function buildExportRow(cost, profile) {
  const t = cost.totals;
  const s = t.tokensSplit ?? {};
  const tokensTotal = t.tokens ?? null;
  return {
    schema_version: profile.schema_version ?? '1.0',
    factory_id: profile.factory_id ?? null,
    factory_name: profile.factory_name ?? null,
    stop: profile.stop ?? 'testing',
    owner_group: profile.owner_group ?? 'QA',
    factory_type: profile.factory_type ?? 'qa',
    factory_domain: profile.factory_domain ?? null,
    agent_tool: profile.agent_tool ?? cost.sources.hosts.join('+'),
    default_method: profile.default_method ?? 'metered',
    scope: profile.scope ?? { includes_subagents: true, includes_retries: true, includes_abandoned_runs: false },
    currency: profile.currency ?? 'USD',
    efficiency_techniques: profile.efficiency_techniques ?? [],
    pipeline: profile.pipeline ?? [],

    work_item_ref: cost.batch,
    work_item_level: 'batch',
    work_item_brief: `test-automation batch '${cost.batch}': ${cost.cases.length} case(s), ${cost.delivered} delivered`,
    sessions: cost.sources.sessions,
    subagent_dispatches: t.dispatches,
    tokens: {
      input: s.input ?? null, output: s.output ?? null,
      cache_read: s.cacheRead ?? null, cache_create: s.cacheWrite ?? null,
    },
    tokens_total: tokensTotal,
    primary_model: cost.sources.models[0] ?? null,
    models_used: cost.sources.models,
    cost_api_equivalent_usd: t.costUsd,
    cost_sources: cost.sources.costSources,
    cache_read_share_pct: tokensTotal && s.cacheRead != null ? round((s.cacheRead / tokensTotal) * 100, 1) : null,

    // Delivery — the pipeline's own receipts, not a guess.
    scenarios_executed: cost.cases.length,
    scenarios_automated: cost.delivered,
    outcomes: cost.outcomes,
    gate: cost.gate ? { verdict: cost.gate.verdict, runs: cost.gate.runs ?? null } : null,
    cost_per_scenario_automated_usd: cost.averages.totalPerDelivered?.costUsd ?? null,
    direct_cost_per_case_usd: cost.averages.directPerCase?.costUsd ?? null,
    overhead_share_pct: cost.overhead.sharePct,

    active_hours: round(t.activeMin / 60, 1),
    tokens_by_agent: cost.byRole ?? {},
    submitted_by: profile.submitted_by ?? null,
    submitted_date: profile.submitted_date ?? null,
    notes: `Generated by tokenomics/build-tokenomics-export.mjs from .agents/automation/${cost.batch}/cost.json (v${cost.v}). active_hours is agent-active time, not wall clock.`,
  };
}

// --- compare: two cost.json files side by side --------------------------------
const fmt = (v, f = (x) => x) => (v == null ? 'n/a' : f(v));
const usd = (v) => fmt(v, (x) => `$${x.toFixed(2)}`);
export function renderCompare(a, b) {
  const row = (label, fa, fb) => `| ${label} | ${fa} | ${fb} |`;
  const s4 = (st, f) => (st ? `${f(st.avg)} / ${f(st.median)} / ${f(st.min)}–${f(st.max)}` : 'n/a');
  return [
    `| metric | ${a.batch} | ${b.batch} |`, '|---|---|---|',
    row('cases / delivered', `${a.cases.length} / ${a.delivered}`, `${b.cases.length} / ${b.delivered}`),
    row('total cost', usd(a.totals.costUsd), usd(b.totals.costUsd)),
    row('per delivered (incl. overhead)', usd(a.averages.totalPerDelivered?.costUsd), usd(b.averages.totalPerDelivered?.costUsd)),
    row('avg direct per case', usd(a.averages.directPerCase?.costUsd), usd(b.averages.directPerCase?.costUsd)),
    row('direct cost avg/median/min–max', s4(a.stats.directCostUsd, (x) => `$${x.toFixed(2)}`), s4(b.stats.directCostUsd, (x) => `$${x.toFixed(2)}`)),
    row('overhead share', fmt(a.overhead.sharePct, (x) => `${x}%`), fmt(b.overhead.sharePct, (x) => `${x}%`)),
    row('active hours', fmt(a.totals.activeMin, (x) => (x / 60).toFixed(1)), fmt(b.totals.activeMin, (x) => (x / 60).toFixed(1))),
    row('gate', a.gate?.verdict ?? 'n/a', b.gate?.verdict ?? 'n/a'),
    row('sessions / dispatches', `${a.sources.sessions} / ${a.totals.dispatches}`, `${b.sources.sessions} / ${b.totals.dispatches}`),
  ].join('\n');
}

function main(argv = process.argv.slice(2)) {
  const ci = argv.indexOf('--compare');
  if (ci !== -1) {
    const [pa, pb] = [argv[ci + 1], argv[ci + 2]];
    const a = safeParse(readFileSync(pa, 'utf8')); const b = safeParse(readFileSync(pb, 'utf8'));
    if (!a || !b) { console.error('compare: could not parse the two cost.json files'); return 1; }
    process.stdout.write(`${renderCompare(a, b)}\n`);
    return 0;
  }
  const val = (name) => { const i = argv.indexOf(name); return i !== -1 ? argv[i + 1] : undefined; };
  const batch = val('--batch');
  const repo = resolve(argv.find((a, i) => !a.startsWith('--') && !['--batch', '--profile', '--out'].includes(argv[i - 1])) ?? process.cwd());
  if (!batch) { console.error('usage: build-tokenomics-export.mjs [repo] --batch <slug> [--profile <path>] [--out <file>] | --compare <a> <b>'); return 1; }
  const profilePath = val('--profile') ?? join(repo, '.agents', 'telemetry', 'factory-profile.json');
  const profile = existsSync(profilePath) ? (safeParse(readFileSync(profilePath, 'utf8')) ?? {}) : {};
  if (!profile.factory_id) console.error(`export: no factory profile at ${profilePath} — identity fields will be null (copy the skill's templates/factory-profile.template.json there and fill it in)`);
  const [cost] = updateBatchCosts(repo, { batch, write: true });
  if (!cost) { console.error(`export: no receipt for batch '${batch}' under ${join(repo, '.agents', 'automation')}`); return 1; }
  const row = buildExportRow(cost, profile);
  const out = val('--out') ?? join(repo, '.agents', 'automation', batch, `${batch}.tokenomics.json`);
  if (argv.includes('--stdout')) process.stdout.write(`${JSON.stringify(row, null, 2)}\n`);
  else { writeFileSync(out, `${JSON.stringify(row, null, 2)}\n`); console.error(`export: wrote ${out}`); }
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exit(main());
